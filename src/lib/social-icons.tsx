// Color per platform (for hover background)
export function getSocialColor(platform: string): string {
  const p = platform.toLowerCase()
  if (p.includes('telegram')) return 'hover:bg-sky-500 hover:text-white hover:border-sky-500'
  if (p.includes('facebook')) return 'hover:bg-blue-600 hover:text-white hover:border-blue-600'
  if (p.includes('instagram')) return 'hover:bg-gradient-to-br hover:from-purple-600 hover:to-pink-500 hover:text-white hover:border-purple-500'
  if (p.includes('reddit')) return 'hover:bg-orange-500 hover:text-white hover:border-orange-500'
  if (p.includes('twitter')) return 'hover:bg-zinc-900 hover:text-white hover:border-zinc-900'
  if (p.includes('discord')) return 'hover:bg-indigo-600 hover:text-white hover:border-indigo-600'
  if (p.includes('youtube')) return 'hover:bg-red-600 hover:text-white hover:border-red-600'
  if (p.includes('whatsapp')) return 'hover:bg-green-500 hover:text-white hover:border-green-500'
  if (p.includes('email') || p.includes('mail')) return 'hover:bg-emerald-600 hover:text-white hover:border-emerald-600'
  return 'hover:bg-emerald-600 hover:text-white hover:border-emerald-600'
}

export function getSocialLabel(platform: string, fallback?: string): string {
  const p = platform.toLowerCase()
  if (p.includes('telegram')) return 'Telegram'
  if (p.includes('facebook')) return 'Facebook'
  if (p.includes('instagram')) return 'Instagram'
  if (p.includes('reddit')) return 'Reddit'
  if (p.includes('twitter')) return 'Twitter / X'
  if (p.includes('discord')) return 'Discord'
  if (p.includes('youtube')) return 'YouTube'
  if (p.includes('whatsapp')) return 'WhatsApp'
  if (p.includes('email') || p.includes('mail')) return 'Email'
  return fallback || platform
}
