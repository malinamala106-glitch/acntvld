export function getSocialIcon(platform: string): React.FC<IconProps> {
  const p = platform.toLowerCase()
  if (p.includes('telegram')) return TelegramIcon
  if (p.includes('facebook') || p === 'fb') return FacebookIcon
  if (p.includes('instagram') || p === 'ig') return InstagramIcon
  if (p.includes('reddit')) return RedditIcon
  if (p.includes('twitter') || p.includes('x.com')) return TwitterIcon
  if (p.includes('discord')) return DiscordIcon
  if (p.includes('youtube') || p.includes('yt')) return YoutubeIcon
  if (p.includes('whatsapp')) return WhatsappIcon
  if (p.includes('email') || p.includes('mail') || p.includes('@')) return EmailIcon
  return LinkIcon
}

